def call(path, body=None, tok=None, method=None, timeout=900):
    req = urllib.request.Request(B + path, data=json.dumps(body).encode() if body is not None else None, method=method,
                                 headers={"Content-Type": "application/json", **({"Authorization": "Bearer " + tok} if tok else {})})
    try:
        r = urllib.request.urlopen(req, timeout=timeout)
        return r.status, json.load(r)
    except urllib.error.HTTPError as e:
        try:
            return e.code, json.load(e)
        except Exception:
            return e.code, {}


def data(r):
    return (r[1] or {}).get("data")


def msg(r):
    e = (r[1] or {}).get("errors") or []
    return e[0].get("message") if e else (r[1] or {}).get("detail")


def check(area, name, cond, evidence=""):
    RESULTS.append({"area": area, "check": name, "pass": bool(cond), "evidence": str(evidence)[:400]})
    print(("PASS " if cond else "FAIL ") + f"[{area}] {name}" + (f"  -- {str(evidence)[:300]}" if evidence != "" else ""), flush=True)


def login(u, p):
    r = call("/api/auth/login", {"username": u, "password": p})
    return data(r)["token"]


ACCOUNTS = {"admin": ("admin", "Admin@123"), "admin2": ("admin2", "Admin@123"), "coordinator": ("coordinator", "Coord@123"),
            "faculty": ("faculty", "Faculty@123"), "club": ("club", "Club@123")}


def tokens():
    return {k: login(*v) for k, v in ACCOUNTS.items()}


def run_validator(schedule_path, extra=()):
    p = subprocess.run([sys.executable, str(VAL), "--data", str(DATA), "--schedule", str(schedule_path), *extra],
                       capture_output=True, text=True)
    return p.returncode, p.stdout


def wait_job(T, jid, url="/api/jobs/"):
    while True:
        j = data(call(url + jid, tok=T["admin"]))
        if j["status"] not in ("RUNNING", "COMPUTING"):
            return j
        time.sleep(3)


