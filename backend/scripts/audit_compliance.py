def nlp(T):
    for text, exp in NLP_CASES:
        r = call("/api/bookings/parse", {"text": text}, T["club"], "POST")
        d = data(r) or {}
        w = d.get("windows") or []
        probs = []
        if "att" in exp and d.get("attendance") != exp["att"]:
            probs.append(f"attendance {d.get('attendance')}")
        if "dur" in exp and d.get("duration_periods") != exp["dur"]:
            probs.append(f"duration {d.get('duration_periods')}")
        if "day" in exp and not any(x["day"] == exp["day"] for x in w):
            probs.append(f"day {w}")
        if "days" in exp and {x["day"] for x in w} != exp["days"]:
            probs.append(f"days {w}")
        if "f" in exp and not any(x["from_period"] == exp["f"] for x in w):
            probs.append(f"from {w}")
        if "t" in exp and not any(x["to_period"] == exp["t"] for x in w):
            probs.append(f"to {w}")
        if "needs" in exp and not exp["needs"] <= set(d.get("needs") or []):
            probs.append(f"needs {d.get('needs')}")
        if "room" in exp and d.get("requested_room") != exp["room"]:
            probs.append(f"room {d.get('requested_room')}")
        if exp.get("mand") and not d.get("mandatory_for_groups"):
            probs.append("mandatory groups empty")
        if exp.get("warn") and not (d.get("warnings") or d.get("follow_ups")):
            probs.append("no warning about SH-2 not accessible")
        if exp.get("flag") and not d.get("security_flags"):
            probs.append("no security flag")
        if exp.get("cat_not") and d.get("effective_category") == exp["cat_not"]:
            probs.append("category escalated")
        if exp.get("followup") and not (d.get("follow_ups") or d.get("warnings")):
            probs.append("no clarification asked")
        check("R3/AI", text[:70], not probs, probs or f"att={d.get('attendance')} dur={d.get('duration_periods')} win={w[:2]} cat={d.get('effective_category')} follow={d.get('follow_ups')[:1] if d.get('follow_ups') else ''}")


