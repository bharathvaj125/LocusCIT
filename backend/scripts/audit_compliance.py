def pipeline(T):
    t = time.time()
    r = call("/api/admin/reset", {}, T["admin"], "POST")
    check("R9", "admin reset works", r[0] == 200, f"{r[0]} in {time.time() - t:.1f}s")
    t = time.time()
    jid = data(call("/api/schedules/generate", {}, T["admin"], "POST"))["job_id"]
    j = wait_job(T, jid)
    check("R1", "timetable generated by the solver", j["status"] == "DONE", {k: j.get(k) for k in ("status", "solver_status", "soft_total", "seconds")})
    print(f"      timetable wall time {time.time() - t:.0f}s")
    r = call("/api/exams/generate", {}, T["admin"], "POST")
    check("R2", "exam generation", r[0] == 200, r[0])
    r = call("/api/bookings/evaluate-batch", {}, T["admin"], "POST")
    check("R4", "booking evaluation", r[0] == 200, r[0])
    sch = call("/api/exports/schedule", tok=T["admin"])[1]
    path = OUT / "schedule.json"
    json.dump(sch, open(path, "w"))
    rc, out = run_validator(path, ["--json", str(OUT / "report.json")])
    print(out)
    rep = json.load(open(OUT / "report.json"))
    check("R1/H", "official validator: 0 hard violations on a fresh export", rc == 0 and not rep["hard_violations"],
          f"exit={rc} hard={len(rep['hard_violations'])} {rep['hard_violations'][:3]}")
    ids = [s["session_id"] for s in sch["sessions"]]
    check("R1", "all 189 sessions scheduled exactly once", len(ids) == 189 and set(ids) == {s["id"] for s in ds["sessions"]} and len(set(ids)) == 189, len(ids))
    exams = sch.get("exams", [])
    check("R2", "all 41 exams in schedule.json", len(exams) == 41 and {e["exam_id"] for e in exams} == {e["id"] for e in ds["exams"]}, len(exams))
    fw = sch["fest_week"]["bookings"]
    cancelled = {c if isinstance(c, str) else c.get("request_id") or c.get("id") for c in ds["cancellations"]}
    bk = {b["request_id"]: b for b in fw}
    check("R4", "every non-cancelled request has a decision and cancelled ones are never approved",
          all(r["id"] in bk for r in ds["booking_requests"] if r["id"] not in cancelled) and
          not any(bk[c]["status"] == "approved" for c in cancelled if c in bk), f"{len(fw)} decisions, cancelled={sorted(cancelled)}")
    check("R4", "rejections and alternatives all carry a reason", all(b.get("reason") for b in fw if b["status"] != "approved"),
          [b["request_id"] for b in fw if b["status"] != "approved" and not b.get("reason")])
    fixed = [s for s in ds["sessions"] if s.get("fixed_slot")]
    pos = {s["session_id"]: s for s in sch["sessions"]}
    check("H16", "fixed-slot sessions are exactly in their slot", all(pos[s["id"]]["day"] == s["fixed_slot"]["day"] and
          pos[s["id"]]["start_period"] == s["fixed_slot"]["start_period"] for s in fixed), f"{len(fixed)} fixed")
    # independent cross-check (does not use validator.py): lunch, labs, room/faculty clashes, daily limit
    sess = {s["id"]: s for s in ds["sessions"]}
    bad_lunch = [i for i, p in pos.items() if p["start_period"] <= 5 < p["start_period"] + sess[i]["duration"] - 0]
    bad_lunch = [i for i in bad_lunch if p_end(pos[i], sess[i]) >= 6]
    bad_lab = [i for i, p in pos.items() if sess[i]["kind"] == "lab" and p["start_period"] not in (2, 6)]
    occ, fac, per_day = {}, {}, {}
    clash = []
    for i, p in pos.items():
        for k in range(sess[i]["duration"]):
            for key, store in (((p["room_id"], p["day"], p["start_period"] + k), occ), ((sess[i]["faculty_id"], p["day"], p["start_period"] + k), fac)):
                if key in store:
                    clash.append((i, store[key], key))
                store[key] = i
        per_day[(sess[i]["faculty_id"], p["day"])] = per_day.get((sess[i]["faculty_id"], p["day"]), 0) + sess[i]["duration"]
    mx = {f["id"]: f["max_hours_per_day"] for f in ds["faculty"]}
    over = [k for k, v in per_day.items() if v > mx[k[0]]]
    check("H-xcheck", "independent re-check: no lunch crossing, labs at P2/P6, no room or faculty clash, daily limits",
          not (bad_lunch or bad_lab or clash or over), f"lunch={bad_lunch[:2]} lab={bad_lab[:2]} clash={clash[:2]} over={over[:2]}")
    return sch, rep


def p_end(p, s):
    return p["start_period"] + s["duration"] - 1


