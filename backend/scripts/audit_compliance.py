def draft(title="Audit event", n=40, day="TUE", f=10, t=11, room=None, cat="club_event", types=None, needs=None):
    return {"title": title, "attendance": n, "duration_periods": t - f + 1, "windows": [{"day": day, "from_period": f, "to_period": t}],
            "needs": needs or [], "room_types": types or ["classroom", "lecture_hall", "seminar_hall"], "requested_room": room,
            "requested_category": cat, "mandatory_for_groups": []}


def booking(T):
    r = call("/api/bookings/submit", draft("Club asks for institute event", 60, "WED", 10, 11, cat="institute_event"), T["club"], "POST")
    sub = data(r)["submissions"][0] if r[0] == 200 else {}
    cat = (sub.get("proposed") or {}).get("effective_category")
    check("R4/AI", "club claiming institute_event is capped to club_event", cat == "club_event", cat)
    sid = sub.get("id")
    r = call(f"/api/bookings/{sid}/decision", {"action": "approve"}, T["club"], "POST")
    check("R4-sec", "requester cannot approve own request", r[0] == 403, msg(r))
    r = call(f"/api/bookings/{sid}/decision", {"action": "approve"}, T["faculty"], "POST")
    check("R4-sec", "faculty cannot approve a request", r[0] == 403, msg(r))
    r = call("/api/bookings/submit", {**draft("hack", 60, "WED", 10, 11), "status": "APPROVED", "role": "admin", "decided_by": "admin"}, T["club"], "POST")
    st = (data(r)["submissions"][0] if r[0] == 200 else {}).get("status")
    check("R4-sec", "client-supplied status/role fields are ignored (stays pending)", st == "PENDING_APPROVAL", st)
    # conflict: two overlapping requests for the same room at once; admin approves both simultaneously
    a = data(call("/api/bookings/submit", draft("Conflict A", 90, "THU", 10, 11, room="SH-1", types=["seminar_hall"]), T["club"], "POST"))["submissions"][0]
    b = data(call("/api/bookings/submit", draft("Conflict B", 90, "THU", 10, 11, room="SH-1", types=["seminar_hall"]), T["faculty"], "POST"))["submissions"][0]
    print("      A:", a["proposed"]["status"], a["proposed"].get("room_id"), "| B:", b["proposed"]["status"], b["proposed"].get("room_id"))
    pa, pb = a["proposed"], b["proposed"]
    check("R4", "overlapping pending requests never share a slot (the later one is recalculated at once)",
          (pa.get("room_id"), pa.get("day"), pa.get("start_period")) != (pb.get("room_id"), pb.get("day"), pb.get("start_period")),
          {"A": [pa.get("room_id"), pa["status"]], "B": [pb.get("room_id"), pb["status"]]})
    res = []
    def go(x, tok):
        res.append(call(f"/api/bookings/{x['id']}/decision", {"action": "approve"}, tok, "POST")[0])
    th = [threading.Thread(target=go, args=(a, T["admin"])), threading.Thread(target=go, args=(b, T["admin2"]))]
    [t.start() for t in th]
    [t.join() for t in th]
    ok_ = [x for x in (call("/api/bookings", tok=T["admin"])[1].get("data") or {}).get("submitted", []) if x["id"] in (a["id"], b["id"]) and x["status"] == "APPROVED"]
    slots = {(x["placement"]["room_id"], x["placement"]["day"], x["placement"]["start_period"]) for x in ok_}
    check("P7", "two simultaneous approvals of overlapping requests: no double booking", len(ok_) == len(slots) and set(res) <= {200, 409}, f"codes={res} approved={len(ok_)} distinct={len(slots)}")
    codes = []
    c = data(call("/api/bookings/submit", draft("Dup", 30, "FRI", 10, 11), T["club"], "POST"))["submissions"][0]
    def dd():
        codes.append(call(f"/api/bookings/{c['id']}/decision", {"action": "approve"}, T["admin"], "POST")[0])
    th = [threading.Thread(target=dd) for _ in range(6)]
    [t.start() for t in th]
    [t.join() for t in th]
    check("P7", "6 simultaneous approvals of one booking: exactly one succeeds", sorted(codes).count(200) == 1, sorted(codes))
    r = call("/api/bookings/submit", draft("Huge", 1200, "FRI", 10, 12), T["club"], "POST")
    d = (data(r)["submissions"][0] if r[0] == 200 else {})
    check("R4", "1,200 people: rejected with a reason", (d.get("proposed") or {}).get("status") == "rejected" and bool(d.get("decision_reason")), d.get("decision_reason"))
    r = call("/api/bookings/submit", draft("Bad room", 30, "FRI", 10, 11, room="XYZ-999"), T["club"], "POST")
    check("R3", "unknown room is refused with a readable message", r[0] == 422, msg(r))
    r = call("/api/bookings/submit", {**draft(), "windows": [{"day": "SAT", "from_period": 10, "to_period": 11}]}, T["club"], "POST")
    check("R3", "weekend window refused", r[0] in (400, 422) , msg(r))
    r = call("/api/bookings/submit", {**draft(), "attendance": 0}, T["club"], "POST")
    check("R3", "invalid attendance refused with a plain message", r[0] == 422, msg(r))
    # coordinator authority over labs
    lab = data(call("/api/bookings/submit", draft("CS lab contest", 40, "TUE", 10, 12, room="CS-LAB-1", types=["lab_cs"], needs=["computers"]), T["faculty"], "POST"))["submissions"][0]
    print("      lab request:", lab["status"], lab["proposed"]["status"], lab.get("routing"))
    if lab["status"] == "PENDING_APPROVAL":
        r = call(f"/api/bookings/{lab['id']}/decision", {"action": "approve"}, T["coordinator"], "POST")
        check("R4-sec", "CSE coordinator may approve a CSE-lab booking", r[0] == 200, msg(r) if r[0] != 200 else r[0])
    elo = data(call("/api/bookings/submit", draft("ECE lab", 30, "TUE", 10, 12, room="ELEC-LAB-1", types=["lab_elec"]), T["faculty"], "POST"))["submissions"][0]
    if elo["status"] == "PENDING_APPROVAL":
        r = call(f"/api/bookings/{elo['id']}/decision", {"action": "approve"}, T["coordinator"], "POST")
