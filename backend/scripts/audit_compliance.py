def perf(T):
    def timed(path, tok):
        t = time.time()
        s = call(path, tok=tok, timeout=120)[0]
        return s, time.time() - t
    lat = []
    def reader():
        lat.append(timed("/api/schedules", T["faculty"]))
    th = [threading.Thread(target=reader) for _ in range(40)]
    t0 = time.time()
    [t.start() for t in th]
    [t.join() for t in th]
    ms = sorted(x[1] * 1000 for x in lat)
    check("P7", "40 simultaneous timetable reads all succeed", all(x[0] == 200 for x in lat), f"{len(lat)} reads, median {statistics.median(ms):.0f}ms, p95 {ms[int(len(ms) * .95) - 1]:.0f}ms, wall {time.time() - t0:.1f}s")
    # responsiveness while the solver runs
    jid = data(call("/api/schedules/generate", {}, T["admin"], "POST"))["job_id"]
    time.sleep(5)
    probes = [timed(p, T["club"]) for p in ("/api/health", "/api/dashboard", "/api/campus/overview", "/api/rooms")]
    check("P7", "API stays responsive while the solver is running (each < 2s)", all(s == 200 and d < 2 for s, d in probes), [f"{s} {d * 1000:.0f}ms" for s, d in probes])
    r = call("/api/bookings/parse", {"text": "seminar hall tomorrow 6pm 100 people"}, T["club"], "POST")
    check("P7", "manual/NL booking tools usable during a solve", r[0] == 200, r[0])
    # reset during the solve must not let the stale result land
    time.sleep(2)
    call("/api/admin/reset", {}, T["admin"], "POST")
    # the solve was running when the reset arrived: give it ample time to finish, then make sure it did not write back
    time.sleep(60)
    jr = call(f"/api/jobs/{jid}", tok=T["admin"])
    d = data(call("/api/dashboard", tok=T["admin"]))
    check("P7", "reset during a solve: the stale solver result is not saved afterwards",
          d["sessions_scheduled"] == 0, f"job lookup={jr[0]} {(data(jr) or {}).get('status')}, sessions_scheduled 60s after reset={d['sessions_scheduled']}")
    for i in range(3):
        call("/api/admin/reset", {}, T["admin"], "POST")
    d = data(call("/api/dashboard", tok=T["admin"]))
    check("P7", "repeated resets leave a clean state", d["sessions_scheduled"] == 0 and d["pending_approvals"] == 0, {k: d[k] for k in ("sessions_scheduled", "pending_approvals", "exams_total")})


